<?php

namespace HarryGulliford\Firebird\Tests;

use Closure;
use HarryGulliford\Firebird\FirebirdConnection;
use Illuminate\Database\Schema\Blueprint;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase as BaseTestCase;

/**
 * Compiles schema SQL without a database connection.
 */
class SchemaGrammarTest extends BaseTestCase
{
    /**
     * @param  list<array<string, mixed>>  $columns  Raw rdb$ rows returned to schema introspection queries.
     */
    protected function compile(string $table, Closure $callback, bool $create = false, string $prefix = '', array $columns = []): array
    {
        $connection = new class(fn () => null, 'database', $prefix) extends FirebirdConnection
        {
            public array $rows = [];

            public function selectFromWriteConnection($query, $bindings = [])
            {
                return $this->rows;
            }
        };

        $connection->rows = $columns;
        $connection->useDefaultSchemaGrammar();

        $blueprint = new Blueprint($connection, $table);

        if ($create) {
            $blueprint->create();
        }

        $callback($blueprint);

        return $blueprint->toSql();
    }

    #[Test]
    public function it_compiles_identity_primary_key_columns()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->id();
            $table->increments('counter')->startingValue(100);
        }, create: true);

        $this->assertSame([
            'create table "users" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL, '
            .'"counter" INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY NOT NULL)',
        ], $sql);
    }

    #[Test]
    public function it_compiles_identity_without_inline_primary_key_when_primary_command_exists()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->increments('id');
            $table->primary('id');
        }, create: true);

        $this->assertSame('create table "users" ("id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL)', $sql[0]);
    }

    #[Test]
    public function it_compiles_column_modifiers_in_firebird_order()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->string('name')->charset('UTF8')->collation('UNICODE_CI')->default("O'Brien");
            $table->enum('status', ['a', "b'c"])->default('a');
            $table->timestamp('seen_at')->useCurrent();
            $table->string('note')->nullable();
        }, create: true);

        $this->assertSame([
            'create table "users" ('
            .'"name" VARCHAR(255) CHARACTER SET UTF8 DEFAULT \'O\'\'Brien\' NOT NULL COLLATE UNICODE_CI, '
            .'"status" VARCHAR(255) DEFAULT \'a\' NOT NULL CHECK ("status" IN (\'a\', \'b\'\'c\')), '
            .'"seen_at" TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL, '
            .'"note" VARCHAR(255))',
        ], $sql);
    }

    #[Test]
    public function it_compiles_one_statement_per_added_column()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->string('a');
            $table->integer('b')->nullable();
        });

        $this->assertSame([
            'ALTER TABLE "users" ADD "a" VARCHAR(255) NOT NULL',
            'ALTER TABLE "users" ADD "b" INTEGER',
        ], $sql);
    }

    #[Test]
    public function it_compiles_drop_and_rename_commands()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->dropUnique(['email']);
            $table->dropIndex(['name']);
            $table->dropColumn(['a', 'b']);
            $table->renameColumn('c', 'd');
            $table->dropPrimary();
        });

        $this->assertSame([
            'ALTER TABLE "users" DROP CONSTRAINT "users_email_unique"',
            'DROP INDEX "users_name_index"',
            'ALTER TABLE "users" DROP "a", DROP "b"',
            'ALTER TABLE "users" ALTER COLUMN "c" TO "d"',
            'execute block as declare c varchar(63); begin '
            .'select trim(rdb$constraint_name) from rdb$relation_constraints '
            .'where rdb$relation_name = \'users\' and rdb$constraint_type = \'PRIMARY KEY\' into :c; '
            .'execute statement \'ALTER TABLE "users" DROP CONSTRAINT "\' || c || \'"\'; end',
        ], $sql);
    }

    #[Test]
    public function it_throws_for_renaming_tables()
    {
        $this->expectException(\LogicException::class);

        $this->compile('users', fn (Blueprint $table) => $table->rename('people'));
    }

    #[Test]
    public function it_compiles_full_length_quoted_constraint_names()
    {
        $sql = $this->compile('a_rather_long_table_name', function (Blueprint $table) {
            $table->primary('id');
            $table->unique('another_long_column_name');
            $table->foreign('another_long_user_id')->references('id')->on('users');
            $table->dropForeign(['another_long_user_id']);
        });

        $this->assertSame([
            'ALTER TABLE "a_rather_long_table_name" ADD CONSTRAINT "a_rather_long_table_name_id_primary" PRIMARY KEY ("id")',
            'ALTER TABLE "a_rather_long_table_name" ADD CONSTRAINT "a_rather_long_table_name_another_long_column_name_unique" UNIQUE ("another_long_column_name")',
            'alter table "a_rather_long_table_name" add constraint "a_rather_long_table_name_another_long_user_id_foreign" foreign key ("another_long_user_id") references "users" ("id")',
            'ALTER TABLE "a_rather_long_table_name" DROP CONSTRAINT "a_rather_long_table_name_another_long_user_id_foreign"',
        ], $sql);
    }

    #[Test]
    public function it_checks_the_prefixed_table_when_dropping_if_exists()
    {
        $sql = $this->compile('users', fn (Blueprint $table) => $table->dropIfExists(), prefix: 'p_');

        $this->assertSame(
            'execute block as begin if (exists(select 1 from rdb$relations where rdb$relation_name = \'p_users\' and rdb$relation_type = 0 and '
            .'(rdb$system_flag is null or rdb$system_flag = 0))) then execute statement \'drop table "p_users"\'; end',
            $sql[0]
        );
    }

    #[Test]
    public function it_compiles_restrict_foreign_key_actions_as_no_action()
    {
        $sql = $this->compile('orders', function (Blueprint $table) {
            $table->foreign('user_id')->references('id')->on('users')->restrictOnDelete()->restrictOnUpdate();
        });

        $this->assertSame(
            'alter table "orders" add constraint "orders_user_id_foreign" foreign key ("user_id") references "users" ("id") on delete no action on update no action',
            $sql[0]
        );
    }

    #[Test]
    public function it_compiles_only_changed_column_attributes()
    {
        $columns = [
            ['name' => 'id', 'field_type' => 16, 'field_sub_type' => 0, 'length' => null, 'precision' => 0, 'scale' => 0, 'charset' => null, 'collation' => null, 'not_null' => 1, 'default' => null, 'identity_type' => 1, 'computed' => null, 'comment' => null],
            ['name' => 'name', 'field_type' => 37, 'field_sub_type' => 0, 'length' => 255, 'precision' => null, 'scale' => 0, 'charset' => 'UTF8', 'collation' => 'UTF8', 'not_null' => 1, 'default' => "DEFAULT 'x'", 'identity_type' => null, 'computed' => null, 'comment' => null],
            ['name' => 'price', 'field_type' => 8, 'field_sub_type' => 2, 'length' => null, 'precision' => 8, 'scale' => -2, 'charset' => null, 'collation' => null, 'not_null' => 0, 'default' => null, 'identity_type' => null, 'computed' => null, 'comment' => null],
        ];

        $sql = $this->compile('users', function (Blueprint $table) {
            $table->id()->change();
            $table->string('name', 100)->nullable()->change();
            $table->decimal('price', 8, 2)->nullable()->change();
        }, columns: $columns);

        $this->assertSame([
            'ALTER TABLE "users" ALTER COLUMN "name" TYPE VARCHAR(100), ALTER COLUMN "name" DROP DEFAULT, ALTER COLUMN "name" DROP NOT NULL',
        ], $sql);

        $sql = $this->compile('users', function (Blueprint $table) {
            $table->decimal('price', 10, 2)->default(0)->change();
        }, columns: $columns);

        $this->assertSame([
            'ALTER TABLE "users" ALTER COLUMN "price" TYPE DECIMAL(10, 2), ALTER COLUMN "price" SET DEFAULT \'0\', ALTER COLUMN "price" SET NOT NULL',
        ], $sql);
    }

    #[Test]
    public function it_compiles_tiny_text_year_and_virtual_columns()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->tinyText('a');
            $table->year('b');
            $table->integer('c')->virtualAs('"b" + 1')->nullable(false)->default(1);
        }, create: true);

        $this->assertSame([
            'create table "users" ("a" VARCHAR(255) NOT NULL, "b" SMALLINT NOT NULL, "c" INTEGER GENERATED ALWAYS AS ("b" + 1))',
        ], $sql);
    }

    #[Test]
    public function it_throws_for_stored_generated_columns()
    {
        $this->expectException(\LogicException::class);

        $this->compile('users', fn (Blueprint $table) => $table->integer('c')->storedAs('1'), create: true);
    }

    #[Test]
    public function it_compiles_float_precision_and_binary_lengths()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->float('a');
            $table->float('b', 10);
            $table->binary('c');
            $table->binary('d', 16, fixed: true);
            $table->binary('e', 100);
        }, create: true);

        $this->assertSame([
            'create table "users" ("a" FLOAT(53) NOT NULL, "b" FLOAT(10) NOT NULL, "c" BLOB SUB_TYPE BINARY NOT NULL, '
            .'"d" BINARY(16) NOT NULL, "e" VARBINARY(100) NOT NULL)',
        ], $sql);
    }

    #[Test]
    public function it_compiles_time_zone_types()
    {
        $sql = $this->compile('users', function (Blueprint $table) {
            $table->timestampTz('a')->useCurrent();
            $table->dateTimeTz('b')->nullable();
            $table->timeTz('c')->nullable();
        }, create: true);

        $this->assertSame([
            'create table "users" ("a" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, '
            .'"b" TIMESTAMP WITH TIME ZONE, "c" TIME WITH TIME ZONE)',
        ], $sql);
    }
}
